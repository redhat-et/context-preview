#!/usr/bin/env node
import { readFile } from "node:fs/promises"
import path from "node:path"
import { reportCacheFile } from "../lib/cache.js"
import { formatReport } from "../lib/report.js"

const args = new Set(process.argv.slice(2))
if (args.has("--help") || args.has("-h")) {
  console.log("Usage: opencode-context-preview [--json]\n\nPrint the latest context preview generated by the OpenCode plugin for this project.")
  process.exit(0)
}

let directory = path.resolve(process.cwd())
let report
while (true) {
  const file = reportCacheFile(directory)
  try {
    report = JSON.parse(await readFile(file, "utf8"))
    break
  } catch {
    const parent = path.dirname(directory)
    if (parent === directory) break
    directory = parent
  }
}

if (report) {
  if (args.has("--json")) console.log(JSON.stringify(report, null, 2))
  else console.log(formatReport(report))
} else {
  console.error("No preview is cached for this directory yet. Start OpenCode with the plugin enabled, then run this command again.")
  process.exitCode = 1
}
